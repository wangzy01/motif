#!/usr/bin/env python3
"""DPG-Bench driver: score one or more sampled run dirs with the Qwen3-VL judge
and write a per-run JSON plus a cross-run comparison (markdown + JSON).

Assumes images already generated by generate_dpg.py under
<samples-dir>/<run_key>/ named ``<item_id>__<run>__seed<N>.png``.

MUST run in the ISOLATED scorer venv /fsx/evan/mot_code/venv-dpg (it imports
transformers + Qwen3-VL). NOT venv-gpu. Read-only w.r.t. training.

Mirrors experiments/eval/run_prompt_following.py's structure.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import score_dpg  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples-dir", required=True,
                    help="dir containing <run_key>/ subdirs of images")
    ap.add_argument("--data", default=str(HERE / "dpg_prompts.jsonl"))
    ap.add_argument("--model", default=score_dpg.DEFAULT_MODEL)
    ap.add_argument("--runs", nargs="+", default=["v1", "b1"])
    ap.add_argument("--device", default="cuda")
    ap.add_argument("--limit", type=int, default=0, help="cap #images per run (0=all)")
    ap.add_argument("--out-dir", default=None)
    # --- ADDITIVE: scorer backend. Default 'qwen3vl' keeps the existing path
    #     byte-for-byte (the running eval-dpg-ssgd job passes no --backend).
    #     'mplug' = ORIGINAL mPLUG VQA scorer (leaderboard-comparable; runs in the
    #     SEPARATE conda env /fsx/evan/miniconda3/envs/dpg-mplug, NOT venv-dpg).
    ap.add_argument("--backend", choices=["qwen3vl", "mplug"], default="qwen3vl",
                    help="qwen3vl (default, internally-consistent) or mplug (leaderboard-comparable)")
    ap.add_argument("--pic-num", type=int, default=4,
                    help="[mplug only] crops of the 2x2 grid: 4 = full upstream protocol")
    ap.add_argument("--modelscope-cache", default="/fsx/evan/modelscope_cache",
                    help="[mplug only] where damo/mplug...coco_large_en is cached")
    args = ap.parse_args()

    samples_dir = Path(args.samples_dir)
    out_dir = Path(args.out_dir) if args.out_dir else samples_dir.parent
    out_dir.mkdir(parents=True, exist_ok=True)

    table = []
    for rk in args.runs:
        rdir = samples_dir / rk
        if not rdir.is_dir():
            print(f"[run] skip {rk}: no dir {rdir}", flush=True)
            continue
        try:
            if args.backend == "mplug":
                # ADDITIVE branch: original mPLUG scorer (separate conda env). The
                # default 'qwen3vl' path below is unchanged.
                import score_dpg_mplug  # noqa: PLC0415
                # modelscope wants 'gpu'/'cpu'/'cuda:N'; map 'cuda' -> 'gpu'.
                ms_device = "gpu" if args.device == "cuda" else args.device
                res = score_dpg_mplug.score_dir(
                    str(rdir), data_path=args.data, device=ms_device,
                    pic_num=args.pic_num, modelscope_cache=args.modelscope_cache,
                    limit=args.limit,
                    detail_path=str(out_dir / f"dpg_{rk}_detail.jsonl"))
            else:
                res = score_dpg.score_dir(
                    str(rdir), data_path=args.data, model_path=args.model,
                    device=args.device, limit=args.limit,
                    detail_path=str(out_dir / f"dpg_{rk}_detail.jsonl"))
            with open(out_dir / f"dpg_{rk}.json", "w", encoding="utf-8") as f:
                json.dump(res, f, ensure_ascii=False, indent=2)
            s = res["summary"]
            row = {"run": rk, "n_images": s["n_images"],
                   "dpg_overall": s["dpg_overall"]}
            row.update({f"l1_{k}": v for k, v in s["l1_category"].items()})
            table.append(row)
        except Exception as e:  # noqa: BLE001
            import traceback
            traceback.print_exc()
            table.append({"run": rk, "error": repr(e)})

    with open(out_dir / "comparison.json", "w", encoding="utf-8") as f:
        json.dump(table, f, ensure_ascii=False, indent=2)

    def fmt(v):
        return f"{v:.2f}" if isinstance(v, (int, float)) else "-"

    l1_keys = ["entity", "attribute", "relation", "global", "other"]
    header = "| run | n | DPG overall | " + " | ".join(l1_keys) + " |"
    sep = "|" + "---|" * (3 + len(l1_keys))
    if args.backend == "mplug":
        # ADDITIVE: mPLUG header (leaderboard-comparable). Default header unchanged.
        lines = ["# DPG-Bench comparison (ORIGINAL mPLUG scorer)", "",
                 "> Scores use the **original mPLUG VQA** model + the upstream",
                 f"> protocol (pic_num={args.pic_num}). These ARE comparable to",
                 "> published DPG-Bench leaderboard numbers **iff** the images were",
                 "> generated as the 2x2 grid (generate_dpg.py --grid 2 -> pic_num=4).",
                 "> See README.md for the full comparability rationale.",
                 "",
                 header, sep]
    else:
        lines = ["# DPG-Bench comparison (Qwen3-VL judge)", "",
                 "> Scores are **internally-consistent only** (Qwen3-VL-as-VQA judge).",
                 "> They are **NOT directly comparable** to published mPLUG DPG-Bench",
                 "> numbers. The legacy mPLUG/fairseq stack is infeasible on this box",
                 "> (python3.12 only). See README.md for the full rationale.",
                 "",
                 header, sep]
    for r in table:
        if "error" in r:
            lines.append(f"| {r['run']} | - | ERROR: {r['error']} | " + " | ".join("-" for _ in l1_keys) + " |")
            continue
        cells = [fmt(r.get(f"l1_{k}")) for k in l1_keys]
        lines.append(f"| {r['run']} | {r.get('n_images','-')} | "
                     f"{fmt(r.get('dpg_overall'))} | " + " | ".join(cells) + " |")
    lines += ["",
              "DPG overall = mean over images of (mean over questions of yes/no, "
              "after dependency-zeroing), ×100. L1 categories are mean per-question "
              "yes-rate (pre-zeroing) within entity/attribute/relation/global/other."]
    md = out_dir / "comparison.md"
    with open(md, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\n[run] wrote {md} and comparison.json", flush=True)


if __name__ == "__main__":
    main()
